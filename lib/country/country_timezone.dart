  /// 传入国家代码（如 'CN'、'US'），返回对应时区
  /// 找不到时返回 null
  static String? getTimezone(String countryCode) {
    return _timezones[countryCode.toUpperCase()];
  }

  /// 传入国家代码，返回时区，找不到时返回默认值
  static String getTimezoneOrDefault(
    String countryCode, {
    String defaultTimezone = 'UTC',
  }) {
    return _timezones[countryCode.toUpperCase()] ?? defaultTimezone;
  }

  /// 传入国家代码和时间，返回转换后的当地时间
  static DateTime? convertToLocalTime(String countryCode, DateTime dateTime) {
    final timezone = getTimezone(countryCode);
    if (timezone == null) return null;
    return convertToTimezone(dateTime, timezone);
  }

  /// 是否支持该国家代码
  static bool isSupported(String countryCode) {
    return _timezones.containsKey(countryCode.toUpperCase());
  }

  /// 获取所有支持的国家代码列表
  static List<String> get supportedCountryCodes => _timezones.keys.toList();
}

